// Generates fixtures/parity.json: the reference output every port (Dart, Kotlin) must match.
// Run: bun scripts/fixtures.ts
import { writeFileSync } from 'node:fs';
import { encode, frameShapes, verify, EFFECT_NAMES, type Ecc } from '../src/index.ts';

const bits = (a: Uint8Array) => Array.from(a).join('');

const matrices = [
  ['hi', 'L'], ['https://example.com', 'Q'], ['HELLO WORLD 123', 'M'], ['héllo wörld ✓', 'H'],
  ['x'.repeat(400), 'M'], ['https://example.com/animated-qr?ref=qrmotion', 'H'],
].map(([text, ecc]) => {
  const qr = encode(text, ecc as Ecc);
  return { text, eccRequested: ecc, ecc: qr.ecc, version: qr.version, size: qr.size, dark: bits(qr.dark), fixed: bits(qr.fixed) };
});

const qr = encode('https://example.com', 'Q');
const round = (v: number) => +v.toFixed(6);
const frames = EFFECT_NAMES.flatMap((effect) => [0, 0.7, 1.9].map((t) => ({
  text: 'https://example.com', ecc: 'Q', effect, t, seed: 1, duration: 2.4,
  shapes: frameShapes(qr, { effect }, t).map((s) => [s.cx, s.cy, s.w, s.h, s.rot, s.r, ...s.fill].map(round)),
})));

const verifyResults = EFFECT_NAMES.map((effect) => ({ effect, ...verify(qr, { effect }, 24) }));

writeFileSync(new URL('../fixtures/parity.json', import.meta.url), JSON.stringify({
  note: 'Generated by scripts/fixtures.ts from the TypeScript reference. shapes: [cx, cy, w, h, rotDeg, radius, r, g, b] in module units incl. 4-module quiet zone. Defaults: ink #17132a, paper #f5f2ea, duration 2.4, quiet 4, seed 1.',
  matrices, frames, verify: verifyResults,
}));
console.log('matrices', matrices.length, 'frames', frames.length);
